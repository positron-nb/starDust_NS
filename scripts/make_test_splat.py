"""Generate a SYNTHETIC Gaussian-splat room for viewer and pipeline testing.

This is NOT a reconstruction. It is a procedurally generated 4 m x 3 m x 2.6 m box
room (floor, walls, ceiling, a door, a window and two furniture blocks), written in
the same binary 3DGS PLY layout that `ns-export gaussian-splat` produces, with the
same z-up convention as nerfstudio's COLMAP dataparser. It lets the web viewer,
format conversion and calibration be tested before any real capture exists.

Example:
    python scripts/make_test_splat.py test/sample_data/synthetic_room.ply
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

SH_C0 = 0.28209479177387814
W, D, H = 4.0, 3.0, 2.6  # room size in metres (x, y, z-up)


def plane(origin, u, v, nu, nv):
    """Grid of points on the parallelogram origin + s*u + t*v, s,t in [0,1]."""
    s, t = np.meshgrid((np.arange(nu) + 0.5) / nu, (np.arange(nv) + 0.5) / nv, indexing="ij")
    pts = np.asarray(origin) + s.reshape(-1, 1) * np.asarray(u) + t.reshape(-1, 1) * np.asarray(v)
    return pts, s.reshape(-1), t.reshape(-1)


def box(lo, hi, spacing):
    lo, hi = np.asarray(lo, float), np.asarray(hi, float)
    size = hi - lo
    out = []
    for axis in range(3):
        a, b = [i for i in range(3) if i != axis]
        for side in (lo[axis], hi[axis]):
            o = lo.copy(); o[axis] = side
            u = np.zeros(3); u[a] = size[a]
            v = np.zeros(3); v[b] = size[b]
            pts, _, _ = plane(o, u, v, max(2, int(size[a] / spacing)), max(2, int(size[b] / spacing)))
            out.append(pts)
    return np.concatenate(out)


def build(spacing: float, rng: np.random.Generator):
    pts_list, col_list = [], []

    def add(pts, colors):
        pts_list.append(pts); col_list.append(np.broadcast_to(colors, pts.shape).copy())

    n = lambda length: max(2, int(length / spacing))  # noqa: E731
    # Floor: warm wooden planks
    p, s, t = plane([0, 0, 0], [W, 0, 0], [0, D, 0], n(W), n(D))
    plank = (np.floor(t * D / 0.2) % 2)[:, None]
    add(p, np.array([0.55, 0.38, 0.24]) * (0.85 + 0.15 * plank) + rng.normal(0, 0.02, (len(p), 3)))
    # Ceiling
    p, _, _ = plane([0, 0, H], [W, 0, 0], [0, D, 0], n(W), n(D))
    add(p, np.array([0.93, 0.93, 0.9]))
    # Walls with skirting band and distinct colours per wall
    walls = [([0, 0, 0], [W, 0, 0], [0.80, 0.75, 0.62]), ([W, 0, 0], [0, D, 0], [0.62, 0.72, 0.78]),
             ([W, D, 0], [-W, 0, 0], [0.78, 0.66, 0.64]), ([0, D, 0], [0, -D, 0], [0.68, 0.76, 0.64])]
    for k, (o, u, base) in enumerate(walls):
        length = np.linalg.norm(u)
        p, s, t = plane(o, u, [0, 0, H], n(length), n(H))
        c = np.tile(np.array(base), (len(p), 1))
        c[t * H < 0.1] = [0.95, 0.95, 0.95]
        if k == 0:  # door
            door = (np.abs(s * length - 0.9) < 0.45) & (t * H < 2.05)
            c[door] = [0.35, 0.22, 0.14]
        if k == 1:  # window
            win = (np.abs(s * length - 1.5) < 0.6) & (np.abs(t * H - 1.5) < 0.5)
            c[win] = [0.75, 0.88, 1.0]
        add(p, c)
    # Furniture: table and sofa blocks
    add(box([2.4, 1.0, 0.0], [3.4, 1.8, 0.75], spacing), np.array([0.30, 0.20, 0.12]))
    add(box([0.3, 2.1, 0.0], [2.1, 2.85, 0.85], spacing), np.array([0.20, 0.32, 0.45]))
    xyz = np.concatenate(pts_list).astype(np.float32)
    rgb = np.clip(np.concatenate(col_list), 0, 1).astype(np.float32)
    return xyz, rgb


def write_ply(path: Path, xyz: np.ndarray, rgb: np.ndarray, spacing: float) -> None:
    count = len(xyz)
    names = ["x", "y", "z", "nx", "ny", "nz", "f_dc_0", "f_dc_1", "f_dc_2", "opacity",
             "scale_0", "scale_1", "scale_2", "rot_0", "rot_1", "rot_2", "rot_3"]
    data = np.zeros((count, len(names)), dtype=np.float32)
    data[:, 0:3] = xyz
    data[:, 6:9] = (rgb - 0.5) / SH_C0
    data[:, 9] = 4.0  # logit(opacity) ~ 0.98
    data[:, 10:13] = np.log(spacing * 0.7)
    data[:, 13] = 1.0  # identity quaternion (w, x, y, z)
    header = "ply\nformat binary_little_endian 1.0\n"
    header += "comment SYNTHETIC test fixture generated by scripts/make_test_splat.py - not a reconstruction\n"
    header += f"element vertex {count}\n" + "".join(f"property float {n}\n" for n in names) + "end_header\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(header.encode("ascii"))
        fh.write(data.tobytes())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out", type=Path)
    ap.add_argument("--spacing", type=float, default=0.03, help="splat spacing in metres (default 0.03)")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    xyz, rgb = build(args.spacing, np.random.default_rng(args.seed))
    write_ply(args.out, xyz, rgb, args.spacing)
    print(f"wrote {len(xyz)} synthetic splats to {args.out} ({args.out.stat().st_size / 2**20:.1f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
